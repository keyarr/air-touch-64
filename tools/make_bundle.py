#!/usr/bin/env python3
"""Build the patch bundle the Android app applies to a user supplied PS Touch APK.

Inputs are host build artifacts only:
  --base    APK produced by adt, before the insets patch and the ARM64 extension library
  --final   APK produced by the full pipeline (insets patched, extension library injected)
  --source  original Adobe APK supplied by the user

The bundle carries no APK. It carries the AIR ARM64 shell generated by adt, a local SWF
transformation for the audited source or legacy SWF/DEX deltas, resource overrides and the extension library.
"""

import argparse
import hashlib
import io
import json
import pathlib
import re
import subprocess
import tempfile
import zipfile

import bsdiff4
from encrypt_bundle import encrypt_bytes
from resource_transforms import apply as transform_resource

SWF_ENTRY = "assets/TTPixel.swf"
RESOURCE_PREFIX = "assets/resource/"
SIGNATURE_NAMES = {"META-INF/MANIFEST.MF"}
SUPPORTED_SWF_INPUT_SHA256 = "d941eab1489b086fadeddfa921d0ffd031a69113b058e81482732c9641664f21"
TRANSFORMED_SWF_SHA256 = "496c3e5009b94ebabecf57beb3f5a0dfade967b8ba6e626cadd2446d0bd538c5"
ADDED_RESOURCE_ENTRIES = {
    "assets/resource/application/uifonts/zh-TW/font.zstrings",
    "assets/resource/application/uifonts/zh/font.zstrings",
    "assets/resource/application/zh-TW/application.zstrings",
    "assets/resource/application/zh/application.zstrings",
}
SOURCE_COPIES = [
    ("assets/CABConfig.xml", "assets/CABConfig.xml"),
    ("assets/META-INF/AIR/extensions/air.com.adobe.cc.PushNotification/library.swf", "assets/META-INF/AIR/extensions/air.com.adobe.cc.PushNotification/META-INF/ANE/library.swf"),
    ("assets/META-INF/AIR/extensions/air.com.adobe.cc.PushNotification/library.swf", "assets/META-INF/AIR/extensions/air.com.adobe.cc.PushNotification/META-INF/ANE/default/library.swf"),
    ("assets/META-INF/AIR/extensions/air.com.adobe.cc.sync.SyncEngine/library.swf", "assets/META-INF/AIR/extensions/air.com.adobe.cc.sync.SyncEngine/META-INF/ANE/library.swf"),
    ("assets/META-INF/AIR/extensions/air.com.adobe.cc.sync.SyncEngine/library.swf", "assets/META-INF/AIR/extensions/air.com.adobe.cc.sync.SyncEngine/META-INF/ANE/default/library.swf"),
    ("res/drawable/mp_warning_32x32_n.png", "res/RJ.png"),
    ("res/raw/startga.html", "res/fE.html"),
    ("res/raw/adobelogo.gif", "res/nZ.gif"),
    ("res/raw/rgba8888", "res/b8"),
    ("res/raw/rgba8888", "res/iv"),
]
SOURCE_COPY_ENTRIES = {entry for _, entry in SOURCE_COPIES}


def is_apk_metadata(name: str) -> bool:
    return name in {"AndroidManifest.xml", "resources.arsc"} or name.startswith("res/")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def is_signature(name: str) -> bool:
    if name in SIGNATURE_NAMES:
        return True
    return name.startswith("META-INF/") and name.endswith((".SF", ".RSA", ".DSA", ".EC"))


def read_zip(path: pathlib.Path) -> dict[str, bytes]:
    with zipfile.ZipFile(path) as archive:
        return {info.filename: archive.read(info) for info in archive.infolist() if not info.is_dir()}


def transform_swf(source_swf: bytes) -> bytes:
    project = pathlib.Path(__file__).resolve().parents[1]
    with tempfile.TemporaryDirectory(prefix="at64-swf-") as temporary:
        temp = pathlib.Path(temporary)
        input_path = temp / "source.swf"
        output_path = temp / "transformed.swf"
        input_path.write_bytes(source_swf)
        process = subprocess.run(
            [
                str(project / "gradlew"),
                "--quiet",
                ":engine:transformSwf",
                f"-PswfInput={input_path}",
                f"-PswfOutput={output_path}",
            ],
            cwd=project,
            check=True,
            capture_output=True,
            text=True,
        )
        output = output_path.read_bytes()
        if process.stdout.strip() != sha256(output):
            raise SystemExit("SWF transformer hash does not match its output")
        return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", type=pathlib.Path, required=True)
    parser.add_argument("--final", type=pathlib.Path, required=True)
    parser.add_argument("--source", type=pathlib.Path, required=True)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    swf_mode = parser.add_mutually_exclusive_group()
    swf_mode.add_argument(
        "--require-local-swf",
        action="store_true",
        help="require the audited SWF input and local transform; reject SWF deltas",
    )
    swf_mode.add_argument(
        "--allow-swf-delta",
        action="store_true",
        help="allow a SWF delta for an experimental unsupported variant",
    )
    parser.add_argument("--name", default="PS Touch Revived ARM64")
    parser.add_argument("--version", default="1.0.0")
    args = parser.parse_args()

    base = read_zip(args.base)
    final = read_zip(args.final)
    source = read_zip(args.source)

    source_copies = []
    for source_entry, entry in SOURCE_COPIES:
        data = source[source_entry]
        if final.get(entry) != data:
            raise SystemExit(f"source copy does not match final APK: {source_entry} -> {entry}")
        source_copies.append({"sourceEntry": source_entry, "entry": entry, "sha256": sha256(data)})

    source_swf = source[SWF_ENTRY]
    final_swf = final[SWF_ENTRY]
    source_swf_hash = sha256(source_swf)
    if args.require_local_swf and source_swf_hash != SUPPORTED_SWF_INPUT_SHA256:
        raise SystemExit(f"unsupported SWF input hash: {source_swf_hash}")
    local_swf = source_swf_hash == SUPPORTED_SWF_INPUT_SHA256
    if not local_swf and not args.allow_swf_delta:
        raise SystemExit(
            f"unsupported SWF input hash: {source_swf_hash}; "
            "pass --allow-swf-delta only for experimental bundles"
        )
    if local_swf:
        transformed_swf = transform_swf(source_swf)
        if sha256(transformed_swf) != TRANSFORMED_SWF_SHA256:
            raise SystemExit("local SWF transformation produced an unexpected hash")
        if transformed_swf != final_swf:
            raise SystemExit(
                "final APK SWF does not match local transformation: "
                f"expected {sha256(transformed_swf)}, got {sha256(final_swf)}"
            )
        swf_patch = None
    else:
        if args.require_local_swf:
            raise SystemExit("local SWF transformation is required")
        transformed_swf = None
        swf_patch = bsdiff4.diff(source_swf, final_swf)

    dex_patches = []
    dex_deltas = {}
    for name in sorted(base):
        if not re.fullmatch(r"classes\d*\.dex", name):
            continue
        if base[name] == final.get(name):
            continue
        delta = bsdiff4.diff(base[name], final[name])
        dex_patches.append(
            {
                "entry": name,
                "patch": f"patches/{name}.bdf",
                "inputSha256": sha256(base[name]),
                "outputSha256": sha256(final[name]),
            }
        )
        dex_deltas[f"patches/{name}.bdf"] = delta

    overrides = []
    resource_transforms = []
    for name in sorted(final):
        if not name.startswith(RESOURCE_PREFIX):
            continue
        if name not in source:
            if name not in ADDED_RESOURCE_ENTRIES:
                raise SystemExit(f"unclassified resource difference: {name}")
            overrides.append({"entry": name, "bundlePath": f"overrides/{name}"})
            continue
        if source.get(name) == final[name]:
            continue
        if name.endswith("application.zstrings") or name.endswith("ttgallerysettingsdetailpanelmodule.cabmod") or name.startswith("assets/resource/application/filters/") and name.endswith(".fs"):
            original = source[name]
            transformed = transform_resource(name, original)
            if transformed != final[name]:
                raise SystemExit(f"resource transformation does not match final APK: {name}")
            resource_transforms.append({
                "entry": name,
                "operation": "resource-v1",
                "inputSha256": sha256(original),
                "outputSha256": sha256(transformed),
            })
            continue
        if name != "assets/resource/application/about.txt":
            raise SystemExit(f"unclassified resource difference: {name}")
        overrides.append({"entry": name, "bundlePath": f"overrides/{name}"})

    native_libs = []
    for name in sorted(final):
        if not name.startswith("lib/") or name in base:
            continue
        native_libs.append({"entry": name, "bundlePath": f"libs/{name}"})

    shell = {}
    for name, data in base.items():
        if is_signature(name):
            continue
        if name == SWF_ENTRY or name.startswith(RESOURCE_PREFIX) or name in SOURCE_COPY_ENTRIES or is_apk_metadata(name):
            continue
        shell[name] = data
    for name, data in final.items():
        if is_apk_metadata(name) and name not in SOURCE_COPY_ENTRIES:
            shell[name] = data

    manifest = {
        "formatVersion": 3 if local_swf else 2,
        "name": args.name,
        "version": args.version,
        "source": {
            "sha256": [sha256(args.source.read_bytes())],
            "requiredEntries": sorted({SWF_ENTRY, *(entry for entry, _ in SOURCE_COPIES)}),
            "swfEntry": SWF_ENTRY,
        },
        "swf": ({
            "operation": "local-transform-v1",
            "sourceSha256": sha256(source_swf),
            "resultSha256": sha256(transformed_swf),
        } if local_swf else {
            "patch": "patches/swf.bdf",
            "sourceSha256": sha256(source_swf),
            "resultSha256": sha256(final_swf),
        }),
        "dexPatches": dex_patches,
        "nativeLibs": native_libs,
        "resourceOverrides": overrides,
        "resourceTransforms": resource_transforms,
        "sourceCopies": source_copies,
        "steps": [
            {"id": "validate", "name": "Validar APK", "description": "Confere hash e arquivos esperados do PS Touch."},
            {
                "id": "swf",
                "name": "Patch do SWF",
                "description": (
                    "Aplica startup, sync local e correção de pintura."
                    if local_swf else "Aplica os patches SWF desta versão legada."
                ),
            },
            {"id": "dex", "name": "Insets Android 16", "description": "Corrige barras e area de gestos no runtime AIR."},
            {"id": "resources", "name": "Recursos", "description": "Textos, about, shaders e branding."},
            {"id": "assemble", "name": "Montar APK", "description": "Runtime ARM64, extensao nativa e alinhamento."},
            {"id": "sign", "name": "Assinar", "description": "Assina com a chave do manager e verifica."},
        ],
    }

    # Self check: shell + source resources + overrides + deltas + patched SWF + libs must
    # reproduce the final APK entry for entry.
    rebuilt = {
        name: data for name, data in base.items()
        if not is_signature(name) and not is_apk_metadata(name)
    }
    rebuilt.update({
        name: data for name, data in final.items()
        if is_apk_metadata(name) and name not in SOURCE_COPY_ENTRIES
    })
    for name, data in source.items():
        if name.startswith(RESOURCE_PREFIX):
            rebuilt[name] = data
    for copy in source_copies:
        rebuilt[copy["entry"]] = source[copy["sourceEntry"]]
    for transform in resource_transforms:
        rebuilt[transform["entry"]] = transform_resource(transform["entry"], source[transform["entry"]])
    for override in overrides:
        rebuilt[override["entry"]] = final[override["entry"]]
    if local_swf:
        check_swf = transform_swf(source_swf)
        if sha256(check_swf) != TRANSFORMED_SWF_SHA256 or check_swf != transformed_swf:
            raise SystemExit("SWF transformation is not deterministic")
        rebuilt[SWF_ENTRY] = check_swf
    else:
        rebuilt[SWF_ENTRY] = bsdiff4.patch(source_swf, swf_patch)
    for lib in native_libs:
        rebuilt[lib["entry"]] = final[lib["entry"]]
    for patch in dex_patches:
        rebuilt[patch["entry"]] = bsdiff4.patch(base[patch["entry"]], dex_deltas[patch["patch"]])
    expected = {name: data for name, data in final.items() if not is_signature(name)}
    if set(rebuilt) != set(expected):
        missing = sorted(set(expected) - set(rebuilt))
        extra = sorted(set(rebuilt) - set(expected))
        raise SystemExit(f"bundle entry set differs; missing={missing} extra={extra}")
    for name, data in expected.items():
        if rebuilt[name] != data:
            raise SystemExit(f"bundle would not reproduce {name}")

    shell = {name: data for name, data in shell.items()}

    args.output.parent.mkdir(parents=True, exist_ok=True)
    archive_buffer = io.BytesIO()
    with zipfile.ZipFile(archive_buffer, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        archive.writestr("manifest.json", json.dumps(manifest, indent=2))
        if swf_patch is not None:
            archive.writestr("patches/swf.bdf", swf_patch)
        for path, data in dex_deltas.items():
            archive.writestr(path, data)
        for name, data in shell.items():
            archive.writestr(f"shell/{name}", data)
        for override in overrides:
            archive.writestr(override["bundlePath"], final[override["entry"]])
        for lib in native_libs:
            archive.writestr(lib["bundlePath"], final[lib["entry"]])

    archive_bytes = archive_buffer.getvalue()
    if args.output.suffix.lower() in {".at64", ".enc"}:
        args.output.write_bytes(encrypt_bytes(args.source, archive_bytes))
    else:
        args.output.write_bytes(archive_bytes)

    print(f"bundle: {args.output} ({args.output.stat().st_size} bytes)")
    print(f"  shell entries: {len(shell)}")
    print(f"  overrides: {len(overrides)}")
    print(f"  dex patches: {len(dex_patches)}")
    print(f"  native libs: {len(native_libs)}")
    if swf_patch is not None:
        print(f"  swf patch: {len(swf_patch)} bytes")
    else:
        print(f"  swf transform: local-transform-v1 ({len(transformed_swf)} output bytes)")
    print(f"  source sha256: {sha256(args.source.read_bytes())}")


if __name__ == "__main__":
    main()
